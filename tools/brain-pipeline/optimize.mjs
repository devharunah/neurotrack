/**
 * Compress and publish the brain model built by build_brain.py.
 *
 *   node tools/brain-pipeline/optimize.mjs
 *
 * Reads tools/brain-pipeline/out/brain.raw.glb + manifest.json and writes:
 *   public/models/brain.<hash>.glb            meshopt + quantized (needs WebAssembly)
 *   tools/brain-pipeline/out/brain.quantized.glb  quantized only (no WebAssembly, ~2.5x
 *       larger); not published, kept for the case where 'wasm-unsafe-eval' must be dropped
 *   src/lib/content/brain-model.json          file names, node table, attribution data
 *
 * Both outputs are validated with the Khronos validator; any error fails the script.
 * Joining, instancing and simplification are switched off so every structure stays its own
 * pickable node with the geometry the Blender step produced.
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../..");
const OUT = join(HERE, "out");
const PUBLIC_MODELS = join(ROOT, "public/models");
const CONTENT_JSON = join(ROOT, "src/lib/content/brain-model.json");
// The package does not export package.json, so resolve the CLI by its install location.
const CLI = join(ROOT, "node_modules/@gltf-transform/cli/bin/cli.js");
const BIOME = join(ROOT, "node_modules/@biomejs/biome/bin/biome");

const KEEP_STRUCTURE = [
  "--join",
  "false",
  "--instance",
  "false",
  "--simplify",
  "false",
  "--flatten",
  "false",
  "--palette",
  "false",
  "--texture-compress",
  "false",
];

function gltfTransform(args) {
  return execFileSync(process.execPath, [CLI, ...args], { encoding: "utf8", stdio: "pipe" });
}

/** Khronos validator severities: 0 error, 1 warning, 2 info, 3 hint. */
function validate(file) {
  const rows = gltfTransform(["validate", file, "--format", "csv"])
    .trim()
    .split(/\r?\n/)
    .slice(1)
    .map((line) => line.split(","));
  const severity = (row) => Number(row.at(-2));
  const errors = rows.filter((row) => severity(row) === 0);
  if (errors.length > 0) {
    throw new Error(`${file}: ${errors.length} validation error(s)\n${errors.join("\n")}`);
  }
  return { numWarnings: rows.filter((row) => severity(row) === 1).length };
}

function publish(tmpFile, stem) {
  const bytes = readFileSync(tmpFile);
  const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
  const name = `${stem}.${hash}.glb`;
  for (const old of readdirSync(PUBLIC_MODELS)) {
    if (old.startsWith(`${stem}.`) && old.endsWith(".glb") && old !== name) {
      rmSync(join(PUBLIC_MODELS, old));
    }
  }
  writeFileSync(join(PUBLIC_MODELS, name), bytes);
  rmSync(tmpFile);
  return { file: `/models/${name}`, bytes: bytes.length };
}

function main() {
  const raw = join(OUT, "brain.raw.glb");
  const manifest = JSON.parse(readFileSync(join(OUT, "manifest.json"), "utf8"));
  mkdirSync(PUBLIC_MODELS, { recursive: true });

  const meshoptTmp = join(OUT, "brain.meshopt.glb");
  gltfTransform(["optimize", raw, meshoptTmp, "--compress", "meshopt", ...KEEP_STRUCTURE]);
  const quantTmp = join(OUT, "brain.quantized.glb");
  gltfTransform(["optimize", raw, quantTmp, "--compress", "quantize", ...KEEP_STRUCTURE]);

  const warnings = validate(meshoptTmp).numWarnings + validate(quantTmp).numWarnings;
  const quantizedBytes = statSync(quantTmp).size;
  const model = publish(meshoptTmp, "brain");

  const nodes = Object.fromEntries(
    Object.entries(manifest.nodes).map(([name, n]) => [
      name,
      { part: n.part, side: n.side, group: n.group, surface: n.surface, anchor: n.anchor },
    ]),
  );
  const content = {
    $comment: "Generated by tools/brain-pipeline/optimize.mjs. Do not edit by hand.",
    model,
    axes: manifest.axes,
    metresPerUnit: Number(manifest.metres_per_unit.toFixed(6)),
    totalTriangles: manifest.total_tris,
    source: manifest.source,
    nodes,
  };
  writeFileSync(CONTENT_JSON, `${JSON.stringify(content, null, 2)}\n`);
  // Keep the generated file in the repo's Biome style so `pnpm check` stays green.
  execFileSync(process.execPath, [BIOME, "format", "--write", CONTENT_JSON], { stdio: "pipe" });

  const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
  console.log(`raw       ${kb(statSync(raw).size)}`);
  console.log(`meshopt   ${kb(model.bytes)}  ${model.file}`);
  console.log(`quantized ${kb(quantizedBytes)}  ${quantTmp} (not published)`);
  console.log(
    `nodes ${Object.keys(nodes).length}, triangles ${manifest.total_tris}, warnings ${warnings}`,
  );
}

main();
