import type { StudyStatus } from "@/lib/behaviour/schemas";

/** Every study, chart and export carries one of these, so synthetic data is never mistaken. */
export function DataKindBadge({ synthetic }: { synthetic: boolean }) {
  return synthetic ? (
    <span
      className="inline-flex items-center rounded-full border border-amber-300 bg-behaviour-soft px-2 py-0.5 text-xs font-semibold uppercase tracking-wide text-behaviour"
      data-testid="synthetic-badge"
    >
      Synthetic data
    </span>
  ) : (
    <span className="inline-flex items-center rounded-full border border-sky-300 bg-sky-50 px-2 py-0.5 text-xs font-semibold uppercase tracking-wide text-sky-800">
      Real participant data
    </span>
  );
}

const STATUS_STYLES: Record<StudyStatus, string> = {
  draft: "bg-paper text-ink-soft",
  active: "bg-emerald-50 text-emerald-800",
  closed: "bg-paper text-muted",
};

export function StatusBadge({ status }: { status: StudyStatus }) {
  return (
    <span className={`rounded-full px-2 py-0.5 text-xs font-medium ${STATUS_STYLES[status]}`}>
      {status}
    </span>
  );
}

export function EthicsNotice() {
  return (
    <p
      role="note"
      className="rounded-lg border border-line bg-card px-4 py-3 text-sm leading-6 text-ink-soft"
    >
      <strong className="font-semibold text-ink">Synthetic by default.</strong> New studies use
      synthetic data. Collecting real participant data needs institutional and ethical approval,
      including applicable Ugandan requirements (for example review by an accredited research ethics
      committee and registration with the Uganda National Council for Science and Technology). A
      study can only switch to real data once its approval reference is recorded.
    </p>
  );
}

export function SyntheticDataNotice() {
  return (
    <p
      role="note"
      className="rounded-lg border border-amber-300 bg-behaviour-soft px-4 py-3 text-sm leading-6 text-behaviour"
      data-testid="synthetic-notice"
    >
      <strong className="font-semibold">Synthetic data.</strong> The participants and observations
      in this study were generated by a seeded simulator with built-in associations, or entered for
      practice. They describe no real people and must not be reported as findings.
    </p>
  );
}

export function ErrorNote({ children }: { children: React.ReactNode }) {
  return (
    <p
      role="alert"
      className="rounded-lg border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-800"
    >
      {children}
    </p>
  );
}

